import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const EXPORT_PREFIX = "appIcon";
const ICONS_DIR = path.resolve(process.cwd(), "public/icons");
const OUTPUT_FILE = path.resolve(
  process.cwd(),
  "components/icons/definitions.generated.ts",
);
const PRESERVE_COLORS = new Set([
  "none",
  "currentcolor",
  "white",
  "#fff",
  "#ffffff",
  "transparent",
  "inherit",
]);

function getAttr(attrs, name) {
  const doubleQuoted = attrs.match(new RegExp(`\\b${name}="([^"]+)"`, "i"));
  if (doubleQuoted) return doubleQuoted[1];

  const singleQuoted = attrs.match(new RegExp(`\\b${name}='([^']+)'`, "i"));
  if (singleQuoted) return singleQuoted[1];

  return null;
}

function toPascalCase(name) {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((segment) => segment[0].toUpperCase() + segment.slice(1))
    .join("");
}

function normalizeColorAttrs(svgBody) {
  return svgBody.replace(
    /\b(fill|stroke)=(["'])([^"']+)\2/gi,
    (match, attr, quote, rawValue) => {
      const value = String(rawValue).trim();
      const lower = value.toLowerCase();

      if (lower.startsWith("url(")) return match;
      if (PRESERVE_COLORS.has(lower)) return `${attr}=${quote}${value}${quote}`;

      return `${attr}=${quote}currentColor${quote}`;
    },
  );
}

function parseSvg(raw, sourceName) {
  const svgOpenTag = raw.match(/<svg\b([^>]*)>/i);
  if (!svgOpenTag) {
    throw new Error(`Invalid SVG (missing <svg>) in ${sourceName}`);
  }

  const attrs = svgOpenTag[1];
  const viewBox = getAttr(attrs, "viewBox");
  const width = getAttr(attrs, "width");
  const height = getAttr(attrs, "height");

  const normalizedViewBox =
    viewBox ??
    (width && height ? `0 0 ${Number(width) || width} ${Number(height) || height}` : "0 0 24 24");

  const body = raw
    .replace(/^[\s\S]*?<svg\b[^>]*>/i, "")
    .replace(/<\/svg>\s*$/i, "")
    .trim();

  if (!body) {
    throw new Error(`Invalid SVG (empty body) in ${sourceName}`);
  }

  return {
    viewBox: normalizedViewBox,
    body: normalizeColorAttrs(body),
  };
}

function build() {
  const files = readdirSync(ICONS_DIR)
    .filter((file) => file.toLowerCase().endsWith(".svg"))
    .sort((a, b) => a.localeCompare(b));

  if (files.length === 0) {
    throw new Error(`No SVG files found in ${ICONS_DIR}`);
  }

  const icons = files.map((file) => {
    const fullPath = path.join(ICONS_DIR, file);
    const raw = readFileSync(fullPath, "utf8");
    const name = file.replace(/\.svg$/i, "");
    const symbol = `${EXPORT_PREFIX}${toPascalCase(name)}`;
    const parsed = parseSvg(raw, file);

    return {
      file,
      name,
      symbol,
      viewBox: parsed.viewBox,
      body: parsed.body,
    };
  });

  const iconNameUnion = icons.map((icon) => JSON.stringify(icon.name)).join(" | ");

  const constDefs = icons
    .map((icon) => {
      return `export const ${icon.symbol}: AppIconDefinition = {\n  name: ${JSON.stringify(icon.name)},\n  viewBox: ${JSON.stringify(icon.viewBox)},\n  body: ${JSON.stringify(icon.body)},\n};`;
    })
    .join("\n\n");

  const recordEntries = icons
    .map((icon) => `  ${JSON.stringify(icon.name)}: ${icon.symbol},`)
    .join("\n");

  const content = `// AUTO-GENERATED by scripts/generate-app-icons.mjs\n// Do not edit this file manually.\n\nexport type AppIconName = ${iconNameUnion};\n\nexport type AppIconDefinition = {\n  name: AppIconName;\n  viewBox: string;\n  body: string;\n};\n\n${constDefs}\n\nexport const appIconDefinitions: Record<AppIconName, AppIconDefinition> = {\n${recordEntries}\n};\n`;

  writeFileSync(OUTPUT_FILE, content, "utf8");
  console.log(`Generated ${icons.length} icons -> ${path.relative(process.cwd(), OUTPUT_FILE)}`);
}

build();
